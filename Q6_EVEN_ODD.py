# WAP to check whether a no. is EVEN or ODD

# Taking input for a no. to check

num=int(input("Enter a no.: "))

# Checking the condition to determine a number is EVEN or ODD

if(num%2==0):
    print(f"{num} is EVEN")
else:
    print(f"{num} is ODD")

