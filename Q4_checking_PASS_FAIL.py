# WAP to check whether a student is "PASS" or "FAIL"
# (Assuming passing marks to be 75 or greater)

# Taking input for marks

marks=int(input("Enter marks: "))

# Checking the PASS condition

if(marks>=75):
  print("Congratulations...You've PASSED the examination")
else:
  print("Better luck next time!!...")

