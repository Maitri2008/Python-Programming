# WAP to input marks in three subjects , calculate the average & print the same.

print("--- Marks & Average Calculator ---")

# Taking input for 3 subjects

a=int(input("Enter marks of Subject 1: "))
b=int(input("Enter marks of Subject 2: "))
c=int(input("Enter marks of Subject 3: "))

# Calculating the average

avg=(a+b+c)/3

# Printing Average

print("Average Marks: ",avg)

